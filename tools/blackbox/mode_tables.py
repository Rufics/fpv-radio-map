#!/usr/bin/env python3
"""Generates the Betaflight mode tables of the fpv.blackbox decoder from the firmware sources.

    python3 -I tools/blackbox/mode_tables.py            # fetch the pinned sources, write the table
    python3 -I tools/blackbox/mode_tables.py --check    # exit 1 when the committed table is stale
    python3 -I tools/blackbox/mode_tables.py --source DIR   # read rc_modes-<ref>.h files from DIR

Betaflight logs the slow frame's flightModeFlags and the FLIGHTMODE event as rcModeActivationMask:
one bit per boxId_e value of src/main/fc/rc_modes.h. Releases insert boxes in the middle of that
enum (3.3 moved BOXBARO, 2025.12 added BOXALTHOLD after BOXMAG), so a bit means a different mode in
each release. This tool reads the enum of every release listed in RELEASES at its pinned git ref
and writes modules/fpv/blackbox/src/mode_tables.inc, which the decoder picks by firmware version.

Only raw.githubusercontent.com is contacted, and only for the refs in RELEASES. The exit code is 2
on a usage error, 1 when --check finds the file stale, 0 otherwise.
"""
import argparse
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "modules" / "fpv" / "blackbox" / "src" / "mode_tables.inc"
SOURCE_URL = "https://raw.githubusercontent.com/betaflight/betaflight/{ref}/src/main/{path}"

RC_MODES = "fc/rc_modes.h"

# (first firmware version the table applies to, git ref, file holding boxId_e at that ref).
# 3.1 kept the enum in rc_controls.h. "master" is pinned to a commit.
RELEASES = [
    ("3.1.0", "v3.1.0", "fc/rc_controls.h"),
    ("3.2.0", "v3.2.0", RC_MODES),
    ("3.3.0", "v3.3.0", RC_MODES),
    ("3.4.0", "3.4.0", RC_MODES),
    ("3.5.0", "3.5.0", RC_MODES),
    ("4.0.0", "4.0.0", RC_MODES),
    ("4.1.0", "4.1.0", RC_MODES),
    ("4.2.0", "4.2.0", RC_MODES),
    ("4.3.0", "4.3.0", RC_MODES),
    ("4.4.0", "4.4.0", RC_MODES),
    ("4.5.0", "4.5.0", RC_MODES),
    ("2025.12.0", "2025.12.2", RC_MODES),
    ("2026.12.0", "c1a17eca71b6cefe5224eb4c3d3aab587cf1b802", RC_MODES),
]


class BoxEnumParser:
    """Reads the boxId_e names, in value order, from the text of a Betaflight header."""

    _ENUM = re.compile(r"typedef\s+enum\s*\{(?P<body>[^}]*)\}\s*boxId_e\s*;")
    _ENTRY = re.compile(r"(?P<name>[A-Z][A-Z0-9_]*)(?:\s*=\s*(?P<value>\w+))?")

    def parse(self, text):
        match = self._ENUM.search(text)
        if not match:
            raise ValueError("no boxId_e enum in the header")
        names = []
        for entry in self._entries(match.group("body")):
            parsed = self._ENTRY.fullmatch(entry)
            if not parsed:
                raise ValueError(f"unexpected boxId_e entry: {entry!r}")
            value = parsed.group("value")
            if value is None:
                names.append(parsed.group("name"))
            elif value.isdigit():
                if int(value) != len(names):
                    raise ValueError(f"{parsed.group('name')} = {value} leaves a hole in boxId_e")
                names.append(parsed.group("name"))
            # NAME = OTHER_NAME is an alias (BOXID_FLIGHTMODE_LAST, CHECKBOX_ITEM_COUNT): no new value.
        if not names or names[0] != "BOXARM":
            raise ValueError("boxId_e does not start with BOXARM, the arm bit every release logs as bit 0")
        return [name for name in names if name != "CHECKBOX_ITEM_COUNT"]

    @staticmethod
    def _entries(body):
        without_comments = re.sub(r"//[^\n]*|/\*.*?\*/", "", body, flags=re.S)
        without_directives = "\n".join(
            line for line in without_comments.splitlines() if not line.strip().startswith("#"))
        return [part.strip() for part in without_directives.split(",") if part.strip()]


class SourceFetcher:
    """Gets a header of one pinned release, from the network or from a local folder."""

    def __init__(self, folder=None):
        self._folder = Path(folder).resolve() if folder else None

    def read(self, ref, path):
        if self._folder is not None:
            return (self._folder / f"rc_modes-{ref}.h").read_text(encoding="utf-8")
        url = SOURCE_URL.format(ref=ref, path=path)
        with urllib.request.urlopen(url, timeout=30) as response:  # noqa: S310 - fixed https host
            return response.read().decode("utf-8")


class ModeTableWriter:
    """Renders the tables as the C++ include the decoder compiles in."""

    def render(self, tables):
        lines = [
            "// Generated by tools/blackbox/mode_tables.py from the Betaflight sources. Do not edit.",
            "// One row per release: the first firmware version it applies to, the git ref it was read",
            "// from, and the boxId_e names in bit order (the mode names logged as rcModeActivationMask).",
            "",
        ]
        for version, ref, names in tables:
            major, minor, patch = (int(part) for part in version.split("."))
            lines.append(f"{{{{{major}, {minor}, {patch}}}, \"{ref}\", {{")
            lines.extend(self._wrap([f'"{self._label(name)}"' for name in names]))
            lines.append("}},")
        return "\n".join(lines) + "\n"

    @staticmethod
    def _label(name):
        return name.removeprefix("BOX")

    @staticmethod
    def _wrap(items, width=100):
        rows, row = [], "    "
        for item in items:
            piece = item + ","
            if len(row) + len(piece) + 1 > width and row.strip():
                rows.append(row.rstrip())
                row = "    "
            row += piece + " "
        if row.strip():
            rows.append(row.rstrip())
        return rows


class ModeTableGenerator:
    """Builds the include from every release in RELEASES."""

    def __init__(self, fetcher, parser=None, writer=None):
        self._fetcher = fetcher
        self._parser = parser or BoxEnumParser()
        self._writer = writer or ModeTableWriter()

    def generate(self):
        tables = []
        for version, ref, path in RELEASES:
            try:
                names = self._parser.parse(self._fetcher.read(ref, path))
            except ValueError as error:
                raise ValueError(f"{ref}/{path}: {error}") from error
            tables.append((version, ref, names))
        return self._writer.render(tables)


class CommandLine:
    """Parses the arguments and runs the generator."""

    def __init__(self, output=OUTPUT):
        self._output = Path(output)

    def run(self, argv):
        parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
        parser.add_argument("--source", help="folder with rc_modes-<ref>.h files instead of the network")
        parser.add_argument("--check", action="store_true", help="only compare with the committed file")
        args = parser.parse_args(argv)
        text = ModeTableGenerator(SourceFetcher(args.source)).generate()
        if args.check:
            current = self._output.read_text(encoding="utf-8") if self._output.exists() else ""
            if current != text:
                print(f"{self._output.name} is stale: run tools/blackbox/mode_tables.py", file=sys.stderr)
                return 1
            return 0
        self._output.write_text(text, encoding="utf-8")
        print(f"wrote {self._output.name} ({len(RELEASES)} releases)")
        return 0


if __name__ == "__main__":
    sys.exit(CommandLine().run(sys.argv[1:]))
