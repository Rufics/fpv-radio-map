"""Tests of the mode table generator: python3 -I -m unittest discover -s tools/blackbox -p '*_test.py'"""
import re
import tempfile
import unittest
from pathlib import Path

from mode_tables import OUTPUT, RELEASES, BoxEnumParser, ModeTableGenerator, ModeTableWriter, SourceFetcher

HEADER = """
#pragma once
typedef enum {
    // ARM flag
    BOXARM = 0,
    // FLIGHT_MODE
    BOXANGLE,
    BOXHORIZON,
    /* a block comment, BOXNOTREAL */
    BOXMAG,
#ifdef USE_ALTHOLD
    BOXALTHOLD,
#endif
    BOXID_FLIGHTMODE_LAST = BOXALTHOLD,
    BOXFAILSAFE,
    CHECKBOX_ITEM_COUNT
} boxId_e;
"""


class FakeFetcher:
    """Answers the same header for every release."""

    def __init__(self, text):
        self.text = text
        self.asked = []

    def read(self, ref, path):
        self.asked.append((ref, path))
        return self.text


class BoxEnumParserTest(unittest.TestCase):
    def test_reads_names_in_value_order(self):
        # #ifdef lines are not values: Betaflight's enum lists every box in every build.
        self.assertEqual(BoxEnumParser().parse(HEADER), ["BOXARM", "BOXANGLE", "BOXHORIZON", "BOXMAG", "BOXALTHOLD", "BOXFAILSAFE"])

    def test_refuses_a_header_without_the_enum(self):
        with self.assertRaisesRegex(ValueError, "no boxId_e"):
            BoxEnumParser().parse("typedef enum { A, B } other_e;")

    def test_refuses_an_explicit_value_that_leaves_a_hole(self):
        with self.assertRaisesRegex(ValueError, "leaves a hole"):
            BoxEnumParser().parse("typedef enum { BOXARM = 0, BOXANGLE = 5 } boxId_e;")

    def test_refuses_an_entry_it_cannot_read(self):
        with self.assertRaisesRegex(ValueError, "unexpected boxId_e entry"):
            BoxEnumParser().parse("typedef enum { BOXARM, BOXANGLE = 1 << 2 } boxId_e;")


class ModeTableWriterTest(unittest.TestCase):
    def test_renders_one_row_per_release_without_the_box_prefix(self):
        text = ModeTableWriter().render([("4.5.0", "4.5.0", ["BOXARM", "BOXANGLE"])])
        self.assertIn('{{4, 5, 0}, "4.5.0", {\n    "ARM", "ANGLE",\n}},\n', text)
        self.assertTrue(text.startswith("// Generated by tools/blackbox/mode_tables.py"))

    def test_wraps_long_rows(self):
        names = [f"BOXMODE{i:02d}" for i in range(30)]
        text = ModeTableWriter().render([("1.0.0", "r", names)])
        self.assertTrue(all(len(line) <= 100 for line in text.splitlines()))
        self.assertEqual(text.count('"MODE'), 30)


class ModeTableGeneratorTest(unittest.TestCase):
    def test_reads_every_pinned_release(self):
        fetcher = FakeFetcher(HEADER)
        text = ModeTableGenerator(fetcher).generate()
        self.assertEqual([ref for ref, _ in fetcher.asked], [ref for _, ref, _ in RELEASES])
        self.assertEqual(text.count('"ALTHOLD"'), len(RELEASES))

    def test_names_the_release_whose_header_it_cannot_read(self):
        with self.assertRaisesRegex(ValueError, re.escape(f"{RELEASES[0][1]}/{RELEASES[0][2]}")):
            ModeTableGenerator(FakeFetcher("nothing here")).generate()

    def test_reads_local_headers_by_ref(self):
        with tempfile.TemporaryDirectory() as folder:
            Path(folder, "rc_modes-4.5.0.h").write_text(HEADER, encoding="utf-8")
            self.assertEqual(SourceFetcher(folder).read("4.5.0", "fc/rc_modes.h"), HEADER)


class CommittedTableTest(unittest.TestCase):
    def test_the_committed_table_has_every_release_in_order(self):
        text = OUTPUT.read_text(encoding="utf-8")
        rows = re.findall(r'^\{\{(\d+), (\d+), (\d+)\}, "([^"]+)", \{', text, flags=re.M)
        self.assertEqual([(f"{a}.{b}.{c}", ref) for a, b, c, ref in rows], [(v, ref) for v, ref, _ in RELEASES])


if __name__ == "__main__":
    unittest.main()
