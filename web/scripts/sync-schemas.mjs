// Copies the JSON schemas owned by the contract (../schemas) into the ui-kit as a TS module,
// so the browser validates with exactly the files the server uses. Run by prebuild/pretest.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, '../../schemas');
const out = resolve(here, '../projects/ui-kit/src/lib/schemas/schemas.generated.ts');

const files = [['mission', join(src, 'mission.schema.json')]];
for (const f of readdirSync(join(src, 'library')).sort()) {
  if (f.endsWith('.schema.json')) files.push([`library/${f.replace('.schema.json', '')}`, join(src, 'library', f)]);
}
let ts = '// GENERATED by scripts/sync-schemas.mjs from ../schemas — do not edit.\n\n';
ts += 'export const SCHEMAS: Record<string, Record<string, unknown>> = {\n';
for (const [key, file] of files) {
  const json = JSON.parse(readFileSync(file, 'utf8'));
  ts += `  ${JSON.stringify(key)}: ${JSON.stringify(json)},\n`;
}
ts += '};\n';
writeFileSync(out, ts);
console.log(`sync-schemas: ${files.length} schemas -> ${out}`);
